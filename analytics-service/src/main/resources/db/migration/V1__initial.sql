CREATE TABLE analytics_metrics (name VARCHAR(80) PRIMARY KEY, value BIGINT NOT NULL DEFAULT 0);
CREATE TABLE product_views (user_id VARCHAR(120) NOT NULL, product_sku VARCHAR(24) NOT NULL,
 category VARCHAR(80), views BIGINT NOT NULL DEFAULT 0,
 last_view TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id, product_sku));
CREATE TABLE processed_events (event_id UUID PRIMARY KEY, processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
